window.getJM26RunnerTopicLabel = function getJM26RunnerTopicLabel(topicId, lang) {
  var map = {
    linear: { en: "Linear Steps", zh: "一元一次" },
    fractions: { en: "Clear the Fraction", zh: "分數係數" },
    double: { en: "Two Bounds", zh: "雙重不等式" },
    flip: { en: "Sign Flip", zh: "符號反轉" },
  };
  var entry = map[topicId];
  if (!entry) return topicId;
  return lang === "zh" ? entry.zh : entry.en;
};

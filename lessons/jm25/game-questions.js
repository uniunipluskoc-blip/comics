window.getJM25QuestionTopic = function getJM25QuestionTopic(sheetKey) {
  if (window.JM25_GAME_GROUPS["cross-method"].indexOf(sheetKey) >= 0) {
    return "cross-method";
  }
  return "factorization";
};

window.getJM25GameTopicLabel = function getJM25GameTopicLabel(topicId, lang) {
  var keyMap = {
    all: "game.jm25.all",
    "cross-method": "game.jm25.crossMethod",
    factorization: "game.jm25.factorization",
  };
  var key = keyMap[topicId];
  if (key && window.I18n && typeof window.I18n.t === 'function') {
    return window.I18n.t(key);
  }
  var preset = (window.JM25_GAME_PRESETS || []).find(function (p) {
    return p.id === topicId;
  });
  if (!preset) return topicId;
  return lang === 'zh' ? preset.labelZh : preset.labelEn;
};

window.getJM25GameQuestions = function getJM25GameQuestions(presetId) {
  var bank = window.JM25_GAME_BANK;
  var groups = window.JM25_GAME_GROUPS;
  var sheetKeys = presetId === "all" ? window.JM25_GAME_ORDER : groups[presetId] || [];

  return sheetKeys.reduce(function (list, key) {
    var tagged = (bank[key] || []).map(function (q) {
      return Object.assign({}, q, { topic: window.getJM25QuestionTopic(key) });
    });
    return list.concat(tagged);
  }, []);
};

window.I18n = {
  lang: "en",
  t: function t(key) {
    var map = window.I18N[window.I18n.lang] || window.I18N.en;
    return map[key] || window.I18N.en[key] || key;
  },
  setLang: function setLang(lang) {
    window.I18n.lang = lang === "zh" ? "zh" : "en";
    localStorage.setItem("s3Lang", window.I18n.lang);
    document.documentElement.lang = window.I18n.lang === "zh" ? "zh-Hant" : "en";
  },
  applyStatic: function applyStatic() {
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      el.textContent = window.I18n.t(key);
    });
    document.querySelectorAll(".lang-btn").forEach(function (btn) {
      btn.classList.toggle("is-active", btn.getAttribute("data-lang") === window.I18n.lang);
    });
  },
};

window.I18n.setLang(localStorage.getItem("s3Lang") || "en");
